-- Leasing MVP schema (PostgreSQL)
-- Standalone domain tables. Does not alter Presourcing M&S tables.
-- Apply this file to the separate leasing_db database.
-- Login identity remains in presourcing_db.public.users; usernames below are audit/owner values only.
-- PostgreSQL foreign keys cannot reference tables in another database, so no cross-database user FKs are used.

BEGIN;

CREATE SCHEMA IF NOT EXISTS leasing;

CREATE TABLE IF NOT EXISTS leasing.customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name TEXT NOT NULL,
    customer_code TEXT UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS leasing.partners (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partner_name TEXT NOT NULL,
    partner_code TEXT UNIQUE,
    contact_name TEXT,
    contact_email TEXT,
    contact_phone TEXT,
    notes TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS leasing.work_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id TEXT NOT NULL UNIQUE,
    customer_id BIGINT REFERENCES leasing.customers(id),
    requester_name TEXT NOT NULL,
    requester_email TEXT,
    requester_division TEXT,
    requester_role TEXT,
    received_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    request_due_date DATE,
    buyer_owner_id TEXT,
    current_stage TEXT NOT NULL DEFAULT 'request_received'
        CHECK (current_stage IN (
            'request_received', 'requirement_review', 'vendor_sourcing',
            'response_monitoring', 'commercial_review', 'result_submission'
        )),
    case_status TEXT NOT NULL DEFAULT 'open'
        CHECK (case_status IN ('open', 'closed', 'cancelled')),
    closure_reason TEXT,
    closed_at TIMESTAMPTZ,
    source_reference TEXT,
    notes TEXT,
    created_by TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (
        (case_status = 'closed' AND closed_at IS NOT NULL)
        OR case_status <> 'closed'
    )
);

CREATE TABLE IF NOT EXISTS leasing.requirements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_item_id BIGINT NOT NULL REFERENCES leasing.work_items(id) ON DELETE CASCADE,
    requirement_no INTEGER NOT NULL,
    order_type TEXT NOT NULL,
    si TEXT,
    area TEXT NOT NULL,
    address TEXT NOT NULL,
    gedung_kawasan TEXT,
    a_end TEXT NOT NULL,
    z_end TEXT,
    bandwidth NUMERIC(14,3) NOT NULL CHECK (bandwidth > 0),
    bandwidth_unit TEXT NOT NULL DEFAULT 'Mbps' CHECK (bandwidth_unit IN ('Mbps', 'Gbps', 'Kbps', 'Other')),
    service_type TEXT NOT NULL,
    special_features TEXT NOT NULL,
    existing_mrc_amount NUMERIC(18,2),
    existing_mrc_currency CHAR(3),
    status TEXT NOT NULL DEFAULT 'open'
        CHECK (status IN ('open', 'in_progress', 'resolved', 'stopped')),
    resolution_note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (work_item_id, requirement_no),
    CHECK (existing_mrc_amount IS NULL OR existing_mrc_amount >= 0),
    CHECK (
        UPPER(BTRIM(REGEXP_REPLACE(order_type, '[^A-Za-z0-9]+', ' ', 'g'))) IN ('PSB', 'PASANG BARU', 'PASANG BARU PSB')
        OR NULLIF(BTRIM(si), '') IS NOT NULL
    )
);

CREATE TABLE IF NOT EXISTS leasing.partner_outreaches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_item_id BIGINT NOT NULL REFERENCES leasing.work_items(id) ON DELETE CASCADE,
    partner_id BIGINT NOT NULL REFERENCES leasing.partners(id),
    outreach_round INTEGER NOT NULL DEFAULT 1 CHECK (outreach_round > 0),
    sent_at TIMESTAMPTZ,
    response_status TEXT NOT NULL DEFAULT 'draft'
        CHECK (response_status IN (
            'draft', 'sent', 'awaiting_response', 'partial_response',
            'responded', 'no_bid', 'cancelled'
        )),
    follow_up_owner_id TEXT,
    next_follow_up_at TIMESTAMPTZ,
    responded_at TIMESTAMPTZ,
    notes TEXT,
    created_by TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (work_item_id, partner_id, outreach_round)
);

CREATE TABLE IF NOT EXISTS leasing.outreach_requirements (
    outreach_id BIGINT NOT NULL REFERENCES leasing.partner_outreaches(id) ON DELETE CASCADE,
    requirement_id BIGINT NOT NULL REFERENCES leasing.requirements(id),
    sent_at TIMESTAMPTZ,
    response_status TEXT NOT NULL DEFAULT 'awaiting_response'
        CHECK (response_status IN (
            'awaiting_response', 'can_provide', 'cannot_provide',
            'needs_clarification', 'no_bid'
        )),
    response_note TEXT,
    PRIMARY KEY (outreach_id, requirement_id)
);

CREATE TABLE IF NOT EXISTS leasing.partner_offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outreach_id BIGINT NOT NULL REFERENCES leasing.partner_outreaches(id) ON DELETE CASCADE,
    version_no INTEGER NOT NULL CHECK (version_no > 0),
    received_at TIMESTAMPTZ,
    valid_until DATE,
    offer_status TEXT NOT NULL DEFAULT 'current'
        CHECK (offer_status IN ('current', 'superseded', 'withdrawn')),
    notes TEXT,
    created_by TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (outreach_id, version_no)
);

CREATE TABLE IF NOT EXISTS leasing.partner_offer_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_id BIGINT NOT NULL REFERENCES leasing.partner_offers(id) ON DELETE CASCADE,
    requirement_id BIGINT NOT NULL REFERENCES leasing.requirements(id),
    feasibility_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (feasibility_status IN (
            'pending', 'can_provide', 'cannot_provide', 'needs_clarification'
        )),
    mrc_amount NUMERIC(18,2),
    otc_amount NUMERIC(18,2),
    currency CHAR(3),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (offer_id, requirement_id),
    CHECK (mrc_amount IS NULL OR mrc_amount >= 0),
    CHECK (otc_amount IS NULL OR otc_amount >= 0),
    CHECK (
        (mrc_amount IS NULL AND otc_amount IS NULL AND currency IS NULL)
        OR currency IS NOT NULL
    )
);

CREATE TABLE IF NOT EXISTS leasing.negotiation_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_line_id BIGINT NOT NULL REFERENCES leasing.partner_offer_lines(id),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    event_type TEXT NOT NULL
        CHECK (event_type IN (
            'initial_offer', 'counter_offer', 'partner_revision',
            'agreed', 'rejected', 'note'
        )),
    mrc_amount NUMERIC(18,2),
    otc_amount NUMERIC(18,2),
    currency CHAR(3),
    notes TEXT,
    created_by TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (mrc_amount IS NULL OR mrc_amount >= 0),
    CHECK (otc_amount IS NULL OR otc_amount >= 0)
);

CREATE TABLE IF NOT EXISTS leasing.commercial_targets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_item_id BIGINT NOT NULL REFERENCES leasing.work_items(id) ON DELETE CASCADE,
    requirement_id BIGINT REFERENCES leasing.requirements(id) ON DELETE CASCADE,
    metric TEXT NOT NULL CHECK (metric IN ('mrc', 'otc')),
    target_amount NUMERIC(18,2) NOT NULL CHECK (target_amount >= 0),
    currency CHAR(3) NOT NULL,
    target_source TEXT NOT NULL DEFAULT 'requester'
        CHECK (target_source IN ('requester', 'buyer_benchmark', 'other')),
    effective_from TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    notes TEXT,
    created_by TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (requirement_id IS NULL OR work_item_id IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS leasing.documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_item_id BIGINT NOT NULL REFERENCES leasing.work_items(id) ON DELETE CASCADE,
    requirement_id BIGINT REFERENCES leasing.requirements(id) ON DELETE SET NULL,
    outreach_id BIGINT REFERENCES leasing.partner_outreaches(id) ON DELETE SET NULL,
    offer_id BIGINT REFERENCES leasing.partner_offers(id) ON DELETE SET NULL,
    document_type TEXT NOT NULL
        CHECK (document_type IN (
            'request_source', 'requirement', 'outreach', 'partner_sph',
            'negotiation', 'result_submission', 'other'
        )),
    original_filename TEXT NOT NULL,
    storage_key TEXT NOT NULL UNIQUE,
    mime_type TEXT,
    size_bytes BIGINT CHECK (size_bytes IS NULL OR size_bytes >= 0),
    uploaded_by TEXT,
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS leasing.result_submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_item_id BIGINT NOT NULL REFERENCES leasing.work_items(id) ON DELETE CASCADE,
    submission_no INTEGER NOT NULL CHECK (submission_no > 0),
    submission_status TEXT NOT NULL DEFAULT 'draft'
        CHECK (submission_status IN ('draft', 'sent', 'cancelled')),
    recipient_name TEXT,
    recipient_email TEXT,
    channel TEXT NOT NULL DEFAULT 'email'
        CHECK (channel IN ('email', 'other')),
    sent_at TIMESTAMPTZ,
    notes TEXT,
    created_by TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (work_item_id, submission_no),
    CHECK (submission_status <> 'sent' OR sent_at IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS leasing.result_submission_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL REFERENCES leasing.result_submissions(id) ON DELETE CASCADE,
    requirement_id BIGINT NOT NULL REFERENCES leasing.requirements(id),
    offer_line_id BIGINT REFERENCES leasing.partner_offer_lines(id),
    result_note TEXT,
    CHECK (result_note IS NULL OR length(result_note) <= 10000)
);

-- A result line may refer to an offer line, or record a decision without a quote.
CREATE UNIQUE INDEX IF NOT EXISTS uq_leasing_submission_line_with_offer
    ON leasing.result_submission_lines (submission_id, requirement_id, offer_line_id)
    WHERE offer_line_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_leasing_submission_line_without_offer
    ON leasing.result_submission_lines (submission_id, requirement_id)
    WHERE offer_line_id IS NULL;

CREATE TABLE IF NOT EXISTS leasing.activity_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_item_id BIGINT NOT NULL REFERENCES leasing.work_items(id) ON DELETE CASCADE,
    event_type TEXT NOT NULL,
    event_summary TEXT NOT NULL,
    actor_id TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Keep updated_at consistent with the rest of the app's PostgreSQL data.
CREATE OR REPLACE FUNCTION leasing.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_customers_updated_at ON leasing.customers;
CREATE TRIGGER trg_customers_updated_at BEFORE UPDATE ON leasing.customers
FOR EACH ROW EXECUTE FUNCTION leasing.set_updated_at();
DROP TRIGGER IF EXISTS trg_partners_updated_at ON leasing.partners;
CREATE TRIGGER trg_partners_updated_at BEFORE UPDATE ON leasing.partners
FOR EACH ROW EXECUTE FUNCTION leasing.set_updated_at();
DROP TRIGGER IF EXISTS trg_work_items_updated_at ON leasing.work_items;
CREATE TRIGGER trg_work_items_updated_at BEFORE UPDATE ON leasing.work_items
FOR EACH ROW EXECUTE FUNCTION leasing.set_updated_at();
DROP TRIGGER IF EXISTS trg_requirements_updated_at ON leasing.requirements;
CREATE TRIGGER trg_requirements_updated_at BEFORE UPDATE ON leasing.requirements
FOR EACH ROW EXECUTE FUNCTION leasing.set_updated_at();
DROP TRIGGER IF EXISTS trg_partner_outreaches_updated_at ON leasing.partner_outreaches;
CREATE TRIGGER trg_partner_outreaches_updated_at BEFORE UPDATE ON leasing.partner_outreaches
FOR EACH ROW EXECUTE FUNCTION leasing.set_updated_at();

-- Keep conditional SI and required technical fields enforced at the database boundary.
CREATE OR REPLACE FUNCTION leasing.validate_requirement_fields()
RETURNS TRIGGER AS $$
DECLARE
    normalized_order_type TEXT;
BEGIN
    IF NEW.bandwidth_unit IS NULL OR BTRIM(NEW.bandwidth_unit) = '' THEN
        NEW.bandwidth_unit := 'Mbps';
    ELSE
        NEW.bandwidth_unit := CASE LOWER(BTRIM(NEW.bandwidth_unit))
            WHEN 'mbps' THEN 'Mbps' WHEN 'gbps' THEN 'Gbps' WHEN 'kbps' THEN 'Kbps' WHEN 'other' THEN 'Other' ELSE NULL END;
        IF NEW.bandwidth_unit IS NULL THEN RAISE EXCEPTION 'Satuan harus Mbps, Gbps, Kbps, atau Other.'; END IF;
    END IF;
    IF BTRIM(COALESCE(NEW.order_type, '')) = '' THEN RAISE EXCEPTION 'Jenis Order wajib diisi.'; END IF;
    IF BTRIM(COALESCE(NEW.area, '')) = '' THEN RAISE EXCEPTION 'Area wajib diisi.'; END IF;
    IF BTRIM(COALESCE(NEW.address, '')) = '' THEN RAISE EXCEPTION 'Alamat wajib diisi; Gedung/Kawasan opsional.'; END IF;
    IF BTRIM(COALESCE(NEW.a_end, '')) = '' THEN RAISE EXCEPTION 'A End wajib diisi.'; END IF;
    IF NEW.bandwidth IS NULL OR NEW.bandwidth <= 0 THEN RAISE EXCEPTION 'Bandwidth harus lebih besar dari nol.'; END IF;
    IF BTRIM(COALESCE(NEW.service_type, '')) = '' THEN RAISE EXCEPTION 'Jasa wajib diisi.'; END IF;
    IF BTRIM(COALESCE(NEW.special_features, '')) = '' THEN RAISE EXCEPTION 'Fitur Khusus wajib diisi; isi Tidak ada jika tidak ada fitur.'; END IF;
    normalized_order_type := UPPER(BTRIM(REGEXP_REPLACE(COALESCE(NEW.order_type, ''), '[^A-Za-z0-9]+', ' ', 'g')));
    IF normalized_order_type NOT IN ('PSB', 'PASANG BARU', 'PASANG BARU PSB') AND BTRIM(COALESCE(NEW.si, '')) = '' THEN
        RAISE EXCEPTION 'SI wajib diisi untuk Jenis Order selain Pasang Baru (PSB).';
    END IF;
    IF NEW.existing_mrc_amount IS NOT NULL THEN
        IF NEW.existing_mrc_amount < 0 THEN RAISE EXCEPTION 'MRC Eksisting tidak boleh negatif.'; END IF;
        IF BTRIM(COALESCE(NEW.existing_mrc_currency, '')) = '' THEN NEW.existing_mrc_currency := 'IDR'; END IF;
    ELSE
        NEW.existing_mrc_currency := NULL;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_requirements_validate_fields_insert ON leasing.requirements;
CREATE TRIGGER trg_requirements_validate_fields_insert BEFORE INSERT ON leasing.requirements
FOR EACH ROW EXECUTE FUNCTION leasing.validate_requirement_fields();
DROP TRIGGER IF EXISTS trg_requirements_validate_fields_update ON leasing.requirements;
CREATE TRIGGER trg_requirements_validate_fields_update
BEFORE UPDATE OF order_type, si, area, address, a_end, bandwidth, bandwidth_unit, service_type, special_features, existing_mrc_amount, existing_mrc_currency
ON leasing.requirements FOR EACH ROW EXECUTE FUNCTION leasing.validate_requirement_fields();

CREATE INDEX IF NOT EXISTS idx_leasing_work_items_status_due
    ON leasing.work_items (case_status, request_due_date);
CREATE INDEX IF NOT EXISTS idx_leasing_work_items_owner_status
    ON leasing.work_items (buyer_owner_id, case_status);
CREATE INDEX IF NOT EXISTS idx_leasing_requirements_work_item
    ON leasing.requirements (work_item_id);
CREATE INDEX IF NOT EXISTS idx_leasing_outreach_follow_up
    ON leasing.partner_outreaches (response_status, next_follow_up_at);
CREATE INDEX IF NOT EXISTS idx_leasing_outreach_work_item
    ON leasing.partner_outreaches (work_item_id);
CREATE INDEX IF NOT EXISTS idx_leasing_offers_outreach
    ON leasing.partner_offers (outreach_id, version_no DESC);
CREATE INDEX IF NOT EXISTS idx_leasing_offer_lines_requirement
    ON leasing.partner_offer_lines (requirement_id);
CREATE INDEX IF NOT EXISTS idx_leasing_submissions_work_item
    ON leasing.result_submissions (work_item_id, submission_no DESC);
CREATE INDEX IF NOT EXISTS idx_leasing_activity_work_item
    ON leasing.activity_events (work_item_id, occurred_at DESC);

COMMIT;

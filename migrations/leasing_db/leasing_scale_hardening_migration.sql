-- Leasing scale, general-service coverage, idempotent import, and query indexes.
-- Apply to leasing_db. This is additive and preserves existing offer/requirement records.
BEGIN;

ALTER TABLE leasing.requirements
  ADD COLUMN IF NOT EXISTS requested_services TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[];

-- Backfill the new generic service list from existing service text. Legacy Project price columns
-- are only used as a one-time compatibility fallback when the row has no service description.
UPDATE leasing.requirements
SET requested_services = ARRAY(
  SELECT DISTINCT BTRIM(part)
  FROM regexp_split_to_table(COALESCE(NULLIF(BTRIM(service_type), ''), ''), E'[;|\\n\\r]+') AS part
  WHERE BTRIM(part) <> ''
)
WHERE COALESCE(array_length(requested_services, 1), 0) = 0
  AND COALESCE(NULLIF(BTRIM(service_type), ''), '') <> '';

UPDATE leasing.requirements
SET requested_services = array_remove(ARRAY[
  CASE WHEN existing_mrc_inet_dedicated_25_amount IS NOT NULL THEN 'Internet Dedicated' END,
  CASE WHEN existing_mrc_metro_25_amount IS NOT NULL THEN 'Metro E' END
]::TEXT[], NULL)
WHERE COALESCE(array_length(requested_services, 1), 0) = 0
  AND (existing_mrc_inet_dedicated_25_amount IS NOT NULL OR existing_mrc_metro_25_amount IS NOT NULL);

ALTER TABLE leasing.commercial_targets
  ADD COLUMN IF NOT EXISTS service_name TEXT;

-- Every service response is tracked independently for an arbitrary service name, with prices and
-- feasibility scoped to one site + partner offer version. No enum of service names is imposed.
CREATE TABLE IF NOT EXISTS leasing.partner_offer_service_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_id BIGINT NOT NULL REFERENCES leasing.partner_offers(id) ON DELETE CASCADE,
    requirement_id BIGINT NOT NULL REFERENCES leasing.requirements(id) ON DELETE CASCADE,
    service_name TEXT NOT NULL CHECK (length(trim(service_name)) BETWEEN 1 AND 160),
    feasibility_status TEXT NOT NULL DEFAULT 'pending'
      CHECK (feasibility_status IN ('pending','can_provide','cannot_provide','needs_clarification')),
    mrc_amount NUMERIC(18,2),
    otc_amount NUMERIC(18,2),
    currency CHAR(3),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (mrc_amount IS NULL OR mrc_amount >= 0),
    CHECK (otc_amount IS NULL OR otc_amount >= 0),
    CHECK ((mrc_amount IS NULL AND otc_amount IS NULL AND currency IS NULL) OR currency IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_leasing_offer_service_line
  ON leasing.partner_offer_service_lines (offer_id, requirement_id, LOWER(BTRIM(service_name)));
CREATE INDEX IF NOT EXISTS idx_leasing_offer_service_lines_requirement
  ON leasing.partner_offer_service_lines (requirement_id, offer_id);

-- Import ledger prevents an identical workbook from silently creating duplicate Work Items.
CREATE TABLE IF NOT EXISTS leasing.import_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fingerprint CHAR(64) NOT NULL,
    uploaded_by TEXT NOT NULL,
    source_filename TEXT,
    grouping_mode TEXT NOT NULL,
    work_item_ids BIGINT[] NOT NULL DEFAULT ARRAY[]::BIGINT[],
    created_count INTEGER NOT NULL DEFAULT 0,
    requirement_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    allow_duplicate BOOLEAN NOT NULL DEFAULT FALSE,
    metadata JSONB NOT NULL DEFAULT '{}'::JSONB
);
CREATE INDEX IF NOT EXISTS idx_leasing_import_batches_fingerprint_user
  ON leasing.import_batches (fingerprint, uploaded_by, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS uq_leasing_import_batches_fingerprint_user
  ON leasing.import_batches (fingerprint, uploaded_by) WHERE allow_duplicate=FALSE;

-- Query paths for paginated workspace and follow-up queue.
CREATE INDEX IF NOT EXISTS idx_leasing_work_items_owner_status_created
  ON leasing.work_items (buyer_owner_id, case_status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_leasing_work_items_created_desc
  ON leasing.work_items (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_leasing_work_items_due_open
  ON leasing.work_items (request_due_date, updated_at DESC) WHERE case_status='open';
CREATE INDEX IF NOT EXISTS idx_leasing_outreaches_followup_owner_due
  ON leasing.partner_outreaches (follow_up_owner_id, next_follow_up_at)
  WHERE response_status IN ('sent','awaiting_response','partial_response');
CREATE INDEX IF NOT EXISTS idx_leasing_outreaches_work_partner_round
  ON leasing.partner_outreaches (work_item_id, partner_id, outreach_round DESC);
CREATE INDEX IF NOT EXISTS idx_leasing_offer_current_outreach
  ON leasing.partner_offers (outreach_id, version_no DESC) WHERE offer_status='current';

-- Case-insensitive lookup index. Application preview reports conflicting case-insensitive IDs;
-- do not make this unique until an existing-data duplicate audit has been completed.
CREATE INDEX IF NOT EXISTS idx_leasing_work_items_request_id_ci
  ON leasing.work_items (LOWER(BTRIM(request_id)));


-- Generic service-level negotiation history; does not depend on any fixed service name.
CREATE TABLE IF NOT EXISTS leasing.partner_service_negotiation_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_line_id BIGINT NOT NULL REFERENCES leasing.partner_offer_service_lines(id) ON DELETE CASCADE,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    event_type TEXT NOT NULL CHECK (event_type IN ('initial_offer','counter_offer','partner_revision','agreed','rejected','note')),
    mrc_amount NUMERIC(18,2),
    otc_amount NUMERIC(18,2),
    currency CHAR(3),
    notes TEXT,
    created_by TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (mrc_amount IS NULL OR mrc_amount >= 0),
    CHECK (otc_amount IS NULL OR otc_amount >= 0),
    CHECK ((mrc_amount IS NULL AND otc_amount IS NULL) OR currency IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS idx_leasing_service_negotiation_line_time
  ON leasing.partner_service_negotiation_events (service_line_id, occurred_at DESC, id DESC);

-- Commercial target lookup: precise target first (site + metric + service), then scoped fallbacks.
CREATE INDEX IF NOT EXISTS idx_leasing_targets_work_metric_requirement_created
  ON leasing.commercial_targets (work_item_id, metric, requirement_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_leasing_targets_service_ci
  ON leasing.commercial_targets (work_item_id, metric, LOWER(BTRIM(service_name)), created_at DESC);

COMMIT;

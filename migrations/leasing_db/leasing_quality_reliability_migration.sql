BEGIN;

ALTER TABLE leasing.work_items
  ADD COLUMN IF NOT EXISTS archived_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS archived_by TEXT,
  ADD COLUMN IF NOT EXISTS archive_reason TEXT;
CREATE INDEX IF NOT EXISTS idx_leasing_work_items_active_owner_due
  ON leasing.work_items (buyer_owner_id, request_due_date, updated_at DESC)
  WHERE archived_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_leasing_work_items_archived_at
  ON leasing.work_items (archived_at DESC) WHERE archived_at IS NOT NULL;

ALTER TABLE leasing.import_batches
  ADD COLUMN IF NOT EXISTS undone_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS undone_by TEXT,
  ADD COLUMN IF NOT EXISTS undone_reason TEXT;

-- Field-level audit events supplement the human-readable activity timeline.
CREATE TABLE IF NOT EXISTS leasing.field_audit_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type TEXT NOT NULL,
  entity_id BIGINT NOT NULL,
  work_item_id BIGINT,
  action TEXT NOT NULL,
  actor_id TEXT NOT NULL,
  reason TEXT,
  before_values JSONB NOT NULL DEFAULT '{}'::JSONB,
  after_values JSONB NOT NULL DEFAULT '{}'::JSONB,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_leasing_field_audit_work_item_time
  ON leasing.field_audit_events (work_item_id, occurred_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_leasing_field_audit_entity
  ON leasing.field_audit_events (entity_type, entity_id, occurred_at DESC);

-- Explicit migration ledger. Existing historical migrations are not retroactively marked here;
-- this release is the first tracked entry. No migration is run automatically by app startup.
CREATE TABLE IF NOT EXISTS leasing.schema_migrations (
  version TEXT PRIMARY KEY,
  description TEXT NOT NULL,
  checksum_sha256 TEXT,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  applied_by TEXT NOT NULL DEFAULT CURRENT_USER
);

-- Leasing admin operations migration
-- Apply to database leasing_db, schema leasing, only after confirming the existing schema is present.
-- Stores a minimal audit record when an admin permanently deletes a mistaken Work Item.

BEGIN;

CREATE TABLE IF NOT EXISTS leasing.work_item_deletion_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    original_work_item_id BIGINT NOT NULL,
    request_id TEXT NOT NULL,
    work_type TEXT,
    project_name TEXT,
    customer_name TEXT,
    requester_name TEXT,
    buyer_owner_id TEXT,
    deleted_by TEXT NOT NULL,
    deletion_reason TEXT NOT NULL CHECK (length(trim(deletion_reason)) >= 10),
    requirements_count INTEGER NOT NULL DEFAULT 0 CHECK (requirements_count >= 0),
    outreaches_count INTEGER NOT NULL DEFAULT 0 CHECK (outreaches_count >= 0),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    deleted_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_leasing_work_item_deletion_audit_deleted_at
    ON leasing.work_item_deletion_audit (deleted_at DESC);
CREATE INDEX IF NOT EXISTS idx_leasing_work_item_deletion_audit_request_id
    ON leasing.work_item_deletion_audit (request_id);

COMMIT;

-- Targeted recovery for the r5 trial errors observed on 2026-10-28.
-- Apply this file to database leasing_db (not presourcing_db).
-- This is deliberately narrower than the full reliability migration: it adds only
-- the missing import-undo columns and field-level audit table, plus archive columns
-- already expected by the current API. Existing rows are preserved.
-- Safe to run more than once. No application startup code runs this automatically.
BEGIN;

ALTER TABLE leasing.work_items
  ADD COLUMN IF NOT EXISTS archived_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS archived_by TEXT,
  ADD COLUMN IF NOT EXISTS archive_reason TEXT;

ALTER TABLE leasing.import_batches
  ADD COLUMN IF NOT EXISTS undone_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS undone_by TEXT,
  ADD COLUMN IF NOT EXISTS undone_reason TEXT;

CREATE TABLE IF NOT EXISTS leasing.field_audit_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type TEXT NOT NULL,
  entity_id BIGINT NOT NULL,
  work_item_id BIGINT,
  action TEXT NOT NULL,
  actor_id TEXT NOT NULL,
  reason TEXT,
  before_values JSONB NOT NULL DEFAULT '{}'::JSONB,
  after_values JSONB NOT NULL DEFAULT '{}'::JSONB,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- The application connects as the verified database owner role. Keep ownership
-- aligned even when this migration is executed via `sudo -u postgres psql`.
ALTER TABLE leasing.field_audit_events OWNER TO presourcing_master;

CREATE INDEX IF NOT EXISTS idx_leasing_field_audit_work_item_time
  ON leasing.field_audit_events (work_item_id, occurred_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_leasing_field_audit_entity
  ON leasing.field_audit_events (entity_type, entity_id, occurred_at DESC);

COMMIT;
